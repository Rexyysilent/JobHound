"""Explicit non-role HTML regions; original provider payloads stay separate."""
from html import unescape
from html.parser import HTMLParser
import re

ROLE_CONTROL_TAGS={'form','fieldset','legend','label','input','select','option',
                   'optgroup','datalist','textarea','button','nav'}
ROLE_CONTROL_ARIA={'form','navigation','listbox','combobox','radiogroup','textbox','button','menu','menuitem'}
_VOID={'area','base','br','col','embed','hr','img','input','link','meta','param','source','track','wbr'}


class PlainFormBoundaryError(ValueError):
    """An explicit form heading has no captured, reliable closing marker."""


_FORM_START = r'(?:application\s+form|application\s+questions)'
_FORM_END = r'(?:submit\s+application|send\s+application|end\s+(?:of\s+)?application\s+form)'
_CLOSED_FORM = '<!--jobhound:closed-semantic-form-->'


def _form_marker(pattern):
    # Whole visible blocks or standalone plain lines only. A sentence about
    # reviewing an application form remains role prose.
    return re.compile(r'(?im)(?:<(?P<block>h[1-6]|p|div)\b[^>]*>\s*'
        r'(?:<(?:span|strong|b|em)\b[^>]*>\s*)*'+pattern+
        r'\s*:?(?:\s*</(?:span|strong|b|em)\s*>)*\s*</(?P=block)\s*>|^[ \t]*'+pattern+r'[ \t]*:?[ \t]*$)')


def _without_plain_forms(source):
    starts = _form_marker(_FORM_START)
    ends = re.compile('(?:'+_form_marker(_FORM_END).pattern.removeprefix('(?im)')+'|'+re.escape(_CLOSED_FORM)+')', re.I | re.M)
    # Embedded JSON-LD may itself contain form markup strings. Those bytes are
    # retained as source payload, but cannot define visible document boundaries.
    scan = re.sub(r'(?is)<(?:script|style|noscript)\b[^>]*>.*?</(?:script|style|noscript)\s*>|<!--.*?-->',
                  lambda match: match.group() if match.group() == _CLOSED_FORM else ' ' * len(match.group()), source)
    output, cursor = [], 0
    while True:
        start = starts.search(scan, cursor)
        if start is None:
            output.append(source[cursor:])
            return ''.join(output).replace(_CLOSED_FORM, '')
        end = ends.search(scan, start.end())
        nested = starts.search(scan, start.end())
        if end is None or (nested is not None and nested.start() < end.start()):
            raise PlainFormBoundaryError('role_plain_form_boundary_uncertain')
        output.extend((source[cursor:start.start()], '\n'))
        cursor = end.end()


def role_control(tag,attrs):
    return tag in ROLE_CONTROL_TAGS or bool(set((attrs.get('role') or '').casefold().split()) & ROLE_CONTROL_ARIA)


class _RoleMarkup(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.stack=[];self.output=[];self.nodes=0

    @property
    def omitted(self):return bool(self.stack and self.stack[-1][1])

    def handle_starttag(self,tag,attrs):
        self.nodes+=1
        if self.nodes>6000 or len(self.stack)>=64:raise ValueError('role_html_structure_limit')
        parent=self.omitted
        omitted=parent or role_control(tag,dict(attrs))
        if omitted and not parent:self.output.append('\n')
        if not omitted:self.output.append(self.get_starttag_text())
        form_boundary=tag=='form' or 'form' in (dict(attrs).get('role') or '').casefold().split()
        if tag not in _VOID:self.stack.append((tag,omitted,form_boundary))

    def handle_startendtag(self,tag,attrs):
        self.handle_starttag(tag,attrs)
        if tag not in _VOID:self.handle_endtag(tag)

    def handle_endtag(self,tag):
        before=self.omitted
        closed_form=False
        if not before and tag not in ROLE_CONTROL_TAGS:self.output.append('</'+tag+'>')
        for index in range(len(self.stack)-1,-1,-1):
            if self.stack[index][0]==tag:
                if before and not self.stack[index][1]:raise ValueError('role_html_control_boundary_uncertain')
                closed_form=before and self.stack[index][2]
                self.stack=self.stack[:index];break
        if before and not self.omitted:
            self.output.append('\n'+(_CLOSED_FORM if closed_form else '')+'\n')

    def handle_data(self,data):
        if not self.omitted:self.output.append(data)

    def handle_entityref(self,name):self.handle_data('&'+name+';')
    def handle_charref(self,name):self.handle_data('&#'+name+';')
    def handle_comment(self,data):
        # The semantic-close marker is generated by this parser, never adopted
        # from provider-authored comments.
        if not self.omitted and '<!--'+data+'-->' != _CLOSED_FORM:self.output.append('<!--'+data+'-->')
    def handle_decl(self,decl):
        if not self.omitted:self.output.append('<!'+decl+'>')
    def handle_pi(self,data):
        if not self.omitted:self.output.append('<?'+data+'>')


def role_markup(value):
    """Remove explicit UI regions before text conversion, preserving other markup.

    Do not decode escaped examples inside actual markup as live form elements.
    Whole encoded HTML is decoded only while there is no actual markup. An
    unclosed omitted region cannot claim that the remainder was safely captured.
    """
    source=value or ''
    if len(source.encode('utf-8'))>2_000_000:raise ValueError('role_html_body_limit')
    for _ in range(2):
        if re.search(r'</?[a-z][^>]*>',source,re.I) or not re.search(r'&(?:amp;)?lt;/?[a-z]',source,re.I):break
        decoded=unescape(source)
        if decoded==source:break
        source=decoded
    parser=_RoleMarkup();parser.feed(source);parser.close()
    if parser.omitted:raise ValueError('role_html_unclosed_control')
    return _without_plain_forms(''.join(parser.output))
